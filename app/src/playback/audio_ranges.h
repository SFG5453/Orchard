#pragma once
#include <QtGlobal>

// YouTube can reject large ranges on otherwise playable stream URLs.
constexpr qint64 audioRangeEnd(qint64 start, qint64 length) {
    return qMin(length - 1, start + 1024 * 1024 - 1);
}
