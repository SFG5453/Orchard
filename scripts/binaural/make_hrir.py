"""Writes app/src/playback/binaural_hrir.h from the MIT KEMAR diffuse-field equalized set.

Usage: make_hrir.py <path to diffuse/elev0> <output header>
Data: https://sound.media.mit.edu/resources/KEMAR/diffuse.tar.Z
Gardner and Martin, "HRTF Measurements of a KEMAR Dummy-Head Microphone", MIT Media Lab, 1994.
"""
import sys

import numpy as np
from scipy.signal import resample_poly

SOURCE_RATE, TARGET_RATE = 44100, 48000


def load(directory, azimuth):
    """Left and right ear responses for a source `azimuth` degrees to the right."""
    raw = np.frombuffer(open(f'{directory}/H0e{azimuth:03d}a.dat', 'rb').read(), dtype='>i2')
    pairs = raw.reshape(-1, 2).astype(np.float64) / 32768.0
    return [resample_poly(pairs[:, ear], TARGET_RATE // 300, SOURCE_RATE // 300) for ear in (0, 1)]


def main(directory, output):
    center_left, center_right = load(directory, 0)
    front_contra, front_ipsi = load(directory, 30)
    surround_contra, surround_ipsi = load(directory, 110)
    center = (center_left + center_right) / 2
    # Unity gain at 1 kHz for a phantom center, the loudest common case.
    taps = len(center)
    response = np.fft.rfft(front_ipsi + front_contra, 4096)
    gain = 1.0 / abs(response[round(1000 * 4096 / TARGET_RATE)])
    filters = {'kCenter': center, 'kFrontIpsi': front_ipsi, 'kFrontContra': front_contra,
               'kSurroundIpsi': surround_ipsi, 'kSurroundContra': surround_contra}
    lines = [
        '// Generated by scripts/binaural/make_hrir.py; do not edit.',
        '// MIT KEMAR diffuse-field equalized HRIRs, resampled to 48 kHz. Copyright 1994 MIT Media',
        '// Laboratory, free to use with citation: Gardner and Martin, "HRTF Measurements of a KEMAR',
        '// Dummy-Head Microphone", MIT Media Lab Perceptual Computing Technical Report 280, 1994.',
        '#pragma once',
        '',
        'namespace binaural_hrir {',
        '',
        f'constexpr int kTaps = {taps};',
    ]
    for name, values in filters.items():
        body = ', '.join(f'{v * gain:.7g}f' for v in values)
        lines.append(f'constexpr float {name}[kTaps] = {{{body}}};')
    lines += ['', '} // namespace binaural_hrir', '']
    with open(output, 'w') as handle:
        handle.write('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
